#!/usr/bin/env node
/**
 * Derives every registry from the rule folders, so a rule is added by
 * creating `rules/<analysis|transformations>/<domain>/<rule>/<rule>.ts` and
 * running `pnpm generate`. Each exported `analyze*` (analysis) or
 * `relocate*` / `rewrite*` (transformations) function becomes one workflow
 * step, in rule-path order and then source order, and the generator writes:
 *
 * - `scripts/analysis/<name>.ts` and `scripts/transformations/<name>.ts`,
 *   one entrypoint per step;
 * - `workflow.yaml` and `transform.yaml`;
 * - the `files` list in `package.json`; and
 * - `tests/rules.generated.ts`, the rule table the fixture runner dispatches on.
 *
 * `pnpm generate --check` (run by the architecture test) fails when any
 * committed file differs from what the generator would write.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const KINDS = [
  {
    kind: "analysis",
    exportPattern: /^export function (analyze[A-Z][A-Za-z0-9]*)\(/gm,
    factory: "createAnalysisEntrypoint",
    workflow: "workflow.yaml",
    nodeId: "analyze-solid-migration-sites",
    nodeName: "Analyze supported Solid 2 migration sites",
    emitName: "Emit all findings once in location order",
  },
  {
    kind: "transformations",
    exportPattern: /^export function ((?:relocate|rewrite)[A-Z][A-Za-z0-9]*)\(/gm,
    factory: "createTransformEntrypoint",
    workflow: "transform.yaml",
    nodeId: "apply-deterministic-solid-2-rewrites",
    nodeName: "Apply the deterministic Solid 2 source rewrites",
    emitName: "Emit the rewrite report once in location order",
  },
];

/** Shipped files that are not derived from the rule folders. */
const STATIC_FILES = [
  "LICENSE",
  "README.md",
  "benchmarks/workspace-pass.ts",
  "benchmarks/workspace-passes.mjs",
  "bin/solid-migration-assistant.mjs",
  "scripts/emit-report.ts",
  "transform.yaml",
  "workflow.yaml",
];

const GENERATED_HEADER = "// Generated by `pnpm generate` (tools/generate.mjs); do not edit.\n";

/**
 * Every rule of one kind: `{ id: "<domain>/<rule>", source, steps }`, where
 * `source` is the production file relative to the package and `steps` are
 * its exported entrypoint functions in source order.
 */
export function discoverRules(kind) {
  const { exportPattern } = KINDS.find((entry) => entry.kind === kind);
  const root = join(packageDirectory, "rules", kind);
  const rules = [];
  for (const domain of sortedDirectories(root)) {
    for (const rule of sortedDirectories(join(root, domain))) {
      const source = `rules/${kind}/${domain}/${rule}/${rule}.ts`;
      if (!existsSync(join(packageDirectory, source))) {
        throw new Error(`${dirname(source)} has no ${rule}.ts production file`);
      }
      const contents = readFileSync(join(packageDirectory, source), "utf8");
      const steps = [...contents.matchAll(exportPattern)].map((match) => match[1]);
      if (steps.length === 0) throw new Error(`${source} exports no entrypoint function`);
      rules.push({ id: `${domain}/${rule}`, source, steps });
    }
  }
  return rules;
}

/** Every generated file, keyed by its path relative to the package. */
export function generatedFiles() {
  const files = new Map();
  const shipped = [...STATIC_FILES];
  const registry = [];

  for (const config of KINDS) {
    const rules = discoverRules(config.kind);
    const steps = rules.flatMap((rule) => rule.steps.map((name) => ({ ...rule, name })));
    for (const step of steps) {
      const path = `scripts/${config.kind}/${step.name}.ts`;
      files.set(
        path,
        `${GENERATED_HEADER}import { ${step.name} } from "../../${step.source}";\n` +
          `import { ${config.factory} } from "../../shared/entrypoint.ts";\n\n` +
          `export default ${config.factory}(${JSON.stringify(step.id)}, ${step.name});\n`,
      );
      shipped.push(path);
    }
    shipped.push(...rules.map((rule) => rule.source));
    files.set(config.workflow, workflowYaml(config, steps));
    registry.push({ config, rules });
  }

  shipped.push(...sharedRuntimeFiles());
  files.set("package.json", packageJson(shipped.sort()));
  files.set("tests/rules.generated.ts", ruleTable(registry));
  return files;
}

/** shared/ modules the workflows import at runtime (type declarations excluded). */
function sharedRuntimeFiles() {
  return readdirSync(join(packageDirectory, "shared"))
    .filter((name) => /\.(?:ts|mjs)$/.test(name) && !name.endsWith(".d.mts"))
    .map((name) => `shared/${name}`);
}

const STEP_FILTERS = `          include:
            - "**/*.js"
            - "**/*.jsx"
            - "**/*.ts"
            - "**/*.tsx"
          exclude:
            - "**/node_modules/**"
            - "**/dist/**"
            - "**/build/**"
            - "**/coverage/**"
            - "**/*.d.ts"
`;

function workflowYaml(config, steps) {
  const ruleSteps = steps.map(
    (step) => `      - name: ${step.name}
        js-ast-grep:
          js_file: scripts/${config.kind}/${step.name}.ts
          base_path: "."
          language: "tsx"
          semantic_analysis: workspace
${STEP_FILTERS}`,
  );
  return `# yaml-language-server: $schema=https://raw.githubusercontent.com/codemod/codemod/refs/heads/main/schemas/workflow.json

version: "1"

nodes:
  - id: ${config.nodeId}
    name: ${config.nodeName}
    type: automatic
    steps:
${ruleSteps.join("")}      - name: ${config.emitName}
        js-ast-grep:
          js_file: scripts/emit-report.ts
          base_path: "."
          language: "tsx"
          max_threads: 1
${STEP_FILTERS}`;
}

function packageJson(shipped) {
  const path = join(packageDirectory, "package.json");
  const manifest = JSON.parse(readFileSync(path, "utf8"));
  manifest.files = shipped;
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function ruleTable(registry) {
  const imports = [];
  const tables = [];
  for (const { config, rules } of registry) {
    const entries = rules.map((rule) => {
      imports.push(`import { ${rule.steps.join(", ")} } from "../${rule.source}";`);
      return `  ${JSON.stringify(rule.id)}: [${rule.steps.join(", ")}],`;
    });
    const name = config.kind === "analysis" ? "ANALYSIS_RULES" : "TRANSFORM_RULES";
    tables.push(`export const ${name} = {\n${entries.join("\n")}\n};`);
  }
  return `${GENERATED_HEADER}${imports.join("\n")}\n\n${tables.join("\n\n")}\n`;
}

function sortedDirectories(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

/** Generated files that would be written, changed, or removed. */
export function staleFiles() {
  const expected = generatedFiles();
  const stale = [];
  for (const [path, contents] of expected) {
    const absolute = join(packageDirectory, path);
    if (!existsSync(absolute) || readFileSync(absolute, "utf8") !== contents) stale.push(path);
  }
  for (const kind of ["analysis", "transformations"]) {
    const directory = join(packageDirectory, "scripts", kind);
    for (const name of existsSync(directory) ? readdirSync(directory) : []) {
      const path = `scripts/${kind}/${name}`;
      if (!expected.has(path)) stale.push(path);
    }
  }
  return stale.sort();
}

function main() {
  const check = process.argv.includes("--check");
  const stale = staleFiles();
  if (check) {
    if (stale.length > 0) {
      console.error(`Generated files are out of date; run \`pnpm generate\`:\n${stale.join("\n")}`);
      process.exit(1);
    }
    console.log("Generated files are up to date.");
    return;
  }
  const expected = generatedFiles();
  for (const path of stale) {
    const absolute = join(packageDirectory, path);
    if (expected.has(path)) {
      mkdirSync(dirname(absolute), { recursive: true });
      writeFileSync(absolute, expected.get(path));
    } else {
      rmSync(absolute);
    }
    console.log(`${expected.has(path) ? "wrote" : "removed"} ${relative(packageDirectory, absolute)}`);
  }
  if (stale.length === 0) console.log("Generated files are up to date.");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
